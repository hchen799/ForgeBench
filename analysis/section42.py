"""Paper Section 4.2 (sweep results): Figs 6-8 and Table 5 from the collected R2 metrics.

  Fig 6  analysis/figures/fig6_dist_csynth.png   csynth marginal distributions (BRAM, LUT, FF util, cycles), designs within ZCU102
  Fig 7  analysis/figures/fig7_coverage.png      csynth joint coverage (BRAM/DSP/LUT util vs cycles, BRAM vs DSP util)
  Fig 8  analysis/figures/fig8_dist_impl.png     impl marginal distributions (power, achieved Fmax, LUT util, cycles)
  Tab 5  analysis/tables_out/table5_impl.{csv,tex}  impl min / mean / max per domain

Inputs: analysis/results_{csynth,impl}/metrics_{gemm,conv,llm}.csv only (results_impl/ also holds the scale-model CSVs, which are
not part of the sweep). Impl rows are the designs that completed place and route (manifest impl=YES).

    python3 -m analysis.section42
"""
import csv
import os

import pandas as pd

from analysis import io
from analysis.dist_csynth import dist_csynth
from analysis.dist_impl import dist_impl
from analysis.plots import fig4_coverage

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOMAINS = [("gemm", "GEMM"), ("conv", "DNN"), ("llm", "LLM")]
FIG = os.path.join(REPO_ROOT, "analysis", "figures")
TAB = os.path.join(REPO_ROOT, "analysis", "tables_out")

# (label, column, scale, format)
TABLE5_ROWS = [
    ("Power (W)", "power_w", 1, "power"),
    ("$F_{\\max}$ (MHz)", "fmax_mhz", 1, "num"),
    ("LUT ($\\times 10^3$)", "lut", 1e-3, "dec1"),
    ("DSP", "dsp", 1, "num"),
    ("BRAM", "bram", 1, "num"),
    ("Latency (cycles $\\times 10^3$)", "cycles", 1e-3, "num"),
    ("Throughput (inference/s)", "throughput", 1, "num"),
]


def load(kind):
    frames = [io.read_metrics_csv(os.path.join(REPO_ROOT, "analysis", f"results_{kind}", f"metrics_{d}.csv")) for d, _ in DOMAINS]
    return pd.concat(frames, ignore_index=True, sort=False)


def fmt(x, kind):
    if kind == "power":
        return f"{x:.2f}"
    if kind == "dec1":
        return f"{x:.1f}"
    if x >= 10000:
        return f"{x / 1000:.1f}K"
    if x >= 10 or float(x).is_integer():        # as R1: integers from 10 up, one decimal below
        return f"{x:,.0f}"
    return f"{x:.1f}"


def table5(impl):
    os.makedirs(TAB, exist_ok=True)
    stats, counts = {}, {}
    for d, _ in DOMAINS:
        sub = impl[impl["domain"] == d]
        counts[d] = len(sub)
        for label, col, scale, _k in TABLE5_ROWS:
            v = pd.to_numeric(sub[col], errors="coerce").dropna() * scale
            stats[(d, col)] = (v.min(), v.mean(), v.max())
    with open(os.path.join(TAB, "table5_impl.csv"), "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["metric", "domain", "n", "min", "mean", "max"])
        for label, col, scale, _k in TABLE5_ROWS:
            for d, _ in DOMAINS:
                w.writerow([col + ("_x1e3" if scale != 1 else ""), d, counts[d], *(f"{x:.6g}" for x in stats[(d, col)])])
    head = " & ".join(f"\\multicolumn{{3}}{{c}}{{{name} ({counts[d]:,})}}" for d, name in DOMAINS)
    lines = [
        "% generated by analysis/section42.py from analysis/results_impl/metrics_{gemm,conv,llm}.csv",
        "\\begin{tabular}{l" + "rrr" * len(DOMAINS) + "}",
        "\\toprule",
        f"Metric & {head} \\\\",
        " ".join(f"\\cmidrule(lr){{{2 + 3 * i}-{4 + 3 * i}}}" for i in range(len(DOMAINS))),
        " & " + " & ".join(["Min & Mean & Max"] * len(DOMAINS)) + " \\\\",
        "\\midrule",
    ]
    for label, col, _s, k in TABLE5_ROWS:
        lines.append(label + " & " + " & ".join(fmt(x, k) for d, _ in DOMAINS for x in stats[(d, col)]) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    with open(os.path.join(TAB, "table5_impl.tex"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {TAB}/table5_impl.{{csv,tex}}  ({', '.join(f'{name} {counts[d]}' for d, name in DOMAINS)}; total {sum(counts.values())})")


def main():
    csynth, impl = load("csynth"), load("impl")
    dist_csynth(df=csynth, out=os.path.join(FIG, "fig6_dist_csynth.png"), feasible=True)
    fig4_coverage(df=csynth, out=os.path.join(FIG, "fig7_coverage.png"))
    dist_impl(df=impl, out=os.path.join(FIG, "fig8_dist_impl.png"))
    table5(impl)


if __name__ == "__main__":
    main()
