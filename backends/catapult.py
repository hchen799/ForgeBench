"""Catapult HLS backend (review concern E1).

Differences from Vitis that this backend has to absorb:

  * Types      `ap_fixed<W,I>` -> `ac_fixed<W,I,true,AC_TRN,AC_WRAP>`; `float` -> `ac_ieee_float<binary32>`
               (Catapult does not synthesize native float arithmetic).
  * Unroll     `#pragma hls_unroll N` sits *before* the `for`, not inside it.
  * Partition  `#pragma HLS array_partition ... cyclic factor=F dim=D` has no
               exact analogue. Catapult's `#pragma hls_interleave F` attaches to
               an array *declaration* and applies to the flattened memory, so it
               is exact for `dim=2` (contiguous in row-major) and only an
               approximation for `dim=1`. See `array_partition` below.
  * Interface  no `m_axi`; the generated top already takes fully-sized array
               parameters, which Catapult maps to memory interfaces natively.
  * Math       `hls::exp/tanh/sqrt` -> ac_math, via the generated
               `forgebench_math.h`. That header supplies its own `namespace hls`
               rather than the kernels being rewritten to call something neutral,
               which keeps the `*_template.cpp` files and the Vitis output
               completely untouched. Same trick as `verification/shim/hls_math.h`.

Target is Nangate 45nm, matching the exploratory `legacy/catapult_exploratory.tcl`.
"""
from backends.base import (
    ToolBackend,
    effective_pragma_factor,
    normalize_data_type, parse_fixed,
    register,
)

QUESTA_BIN = "/tools/software/siemens/questa/2026.1_2/questasim/bin"   # SCVerify RTL simulation (cosim task)

DEFAULT_LIBS = (
    "nangate-45nm_beh -- -rtlsyntool DesignCompiler -vendor Nangate -technology 045nm",
    "ram_nangate-45nm-singleport_beh",
)

# ac_math PWL approximations are NOT bit-identical to Vitis hls_math. Designs run
# through the verification harness on this backend need a looser tolerance.
# `data_type: "float"` emits ac_ieee_float<binary32> (see type_decl), which the
# float overloads below do not cover: math on float designs is not wired yet
# (GEMM, the only domain on this backend, uses none).
MATH_HEADER = """\
// Auto-generated by ForgeBench for the Catapult backend.
//
// The generated kernels call hls::exp/tanh/sqrt/... because that is what the
// shared *_template.cpp files contain. Rather than rewrite every template (and
// perturb the Vitis output, which the committed metrics were produced from),
// this header re-provides `namespace hls` on top of ac_math. Same approach as
// verification/shim/hls_math.h, which does it for a stock g++.
#ifndef FORGEBENCH_MATH_H
#define FORGEBENCH_MATH_H

#include <cmath>
#include <ac_fixed.h>
#include <ac_math/ac_pow_pwl.h>   // ac_exp_pwl lives here, not in ac_exp_pwl.h
#include <ac_math/ac_sqrt_pwl.h>
#include <ac_math/ac_tanh_pwl.h>

namespace hls {

// These are piecewise-linear approximations and are NOT bit-identical to Vitis
// hls_math. Designs run through the verification harness on this backend need a
// looser tolerance, or `data_type: "float"` (below).
//
// ac_math constrains signedness by mathematical domain, so the signed data_t the
// generators emit cannot be passed straight through:
//   ac_exp_pwl  - output must be unsigned (exp is always positive)
//   ac_sqrt_pwl - input AND output must be unsigned
//   ac_tanh_pwl - fully generic
// Hence the unsigned intermediates below.

template <typename T> inline T exp(const T &x) {
  ac_fixed<T::width, T::i_width, false> u;
  ac_math::ac_exp_pwl(x, u);
  return T(u);
}

template <typename T> inline T sqrt(const T &x) {
  // Negative inputs are outside sqrt's domain; clamp rather than wrap, which is
  // what the fixed-point kernels (variance + epsilon, etc.) expect anyway.
  ac_fixed<T::width, T::i_width, false> in(x < 0 ? T(0) : x), u;
  ac_math::ac_sqrt_pwl(in, u);
  return T(u);
}

template <typename T> inline T tanh(const T &x) {
  T out;
  ac_math::ac_tanh_pwl(x, out);
  return out;
}

// Non-template overloads for plain C scalars (exact libm semantics). Note that
// `data_type: "float"` designs use ac_ieee_float<binary32>, not C float.
inline float exp(float x)    { return std::exp(x); }
inline float sqrt(float x)   { return std::sqrt(x); }
inline float tanh(float x)   { return std::tanh(x); }
inline double exp(double x)  { return std::exp(x); }
inline double sqrt(double x) { return std::sqrt(x); }
inline double tanh(double x) { return std::tanh(x); }

// TODO(conv/llm widening): pow/sin/cos are float-only for now. The ac_math
// equivalents are ac_pow_pwl and ac_sincos_cordic; the latter returns sin and
// cos together, so the RoPE kernels in llm/ need restructuring rather than a
// straight substitution.
inline float powf(float b, float e) { return std::pow(b, e); }
inline float sin(float x)  { return std::sin(x); }
inline float cos(float x)  { return std::cos(x); }

}  // namespace hls

#endif  // FORGEBENCH_MATH_H
"""


@register
class CatapultBackend(ToolBackend):
    name = "catapult"

    def __init__(self):
        # Partition requests are recorded rather than emitted in place, because
        # `hls_interleave` belongs on the declaration. `generate_top_function`
        # drains this before emitting the BRAM declarations.
        self._partitions = {}
        self._dropped_partitions = []

    # -- types -------------------------------------------------------------

    def type_decl(self, data_type):
        fx = parse_fixed(data_type)
        if fx is None:
            t = normalize_data_type(data_type)[1]
            # Catapult does not synthesize native `float` arithmetic (CIN-290); ac_ieee_float<binary32> is its synthesizable IEEE
            # single type (round-to-nearest-even, subnormals kept: the same results as C `float` for + and *).
            return "ac_ieee_float<binary32>" if t == "float" else t
        # Signed. Without explicit modes the type is truncate + wrap, matching the ap_fixed defaults (see backends.base.parse_fixed).
        w, i, q, o = fx
        return f"ac_fixed<{w},{i},true,AC_{q.upper()},AC_{o.upper()}>"

    def type_suffix(self, data_type):
        """Tool-neutral suffix.

        Deliberately not derived from `type_decl` — spelling the quantization
        mode into every function name (`ac_fixed_16_5_true_AC_TRN_AC_WRAP_`)
        would be unreadable, and these names only need to be unique per design.
        """
        fx = parse_fixed(data_type)
        if fx is None:
            if data_type.replace(" ", "") == "ac_ieee_float<binary32>":    # callers may pass the type_decl spelling back in
                return "float"
            return normalize_data_type(data_type)[1]
        w, i, q, o = fx
        mode = "" if (q, o) == ("trn", "wrap") else f"{q}_{o}_"      # default modes keep the historical suffix
        return f"fixed_{w}_{i}_{mode}"

    # -- includes ----------------------------------------------------------

    def includes_top_cpp(self):
        return [
            "#include <stdio.h>",
            "#include <iostream>",
            "#include <fstream>",
            "#include <cstdlib>",
            "#include <ac_fixed.h>",
            "#include <ac_std_float.h>",
            "#include <ac_int.h>",
            "#include <stdlib.h>",
            "#include <cstdint>",
            '#include "forgebench_math.h"',
        ]

    def includes_top_h(self):
        return ["#include <ac_fixed.h>", "#include <ac_std_float.h>"]

    def includes_tb(self):
        return [
            "#include <stdio.h>",
            "#include <stdlib.h>",
            "#include <math.h>",
            "#include <ac_fixed.h>",
            "#include <ac_std_float.h>",
            '#include "top.h"  // Include the top function declaration',
            "#include <mc_scverify.h>",
            "",
            "// ac_fixed has no conversion operator to double/float (only to_double()); the testbench converts through these.",
            "inline double fb_to_double(double x) { return x; }",
            "template <int W, int I, bool S, ac_q_mode Q, ac_o_mode O>",
            "inline double fb_to_double(const ac_fixed<W, I, S, Q, O> &x) { return x.to_double(); }",
            "template <ac_ieee_float_format F>",
            "inline double fb_to_double(const ac_ieee_float<F> &x) { return x.to_float(); }",
        ]

    def tb_cast(self, expr, ctype):
        return f"fb_to_double({expr})" if ctype == "double" else f"({ctype})fb_to_double({expr})"

    def zero(self):
        return "data_t(0)"      # ac_ieee_float has no assignment from int

    # SCVerify (Catapult's C-sim and RTL-vs-C flow) needs its own main, a marked top call and its own return.
    def tb_main(self):
        return "CCS_MAIN(int argc, char *argv[]) {"

    def tb_call(self, top_func_name):
        return f"CCS_DESIGN({top_func_name})"

    def tb_return(self, value):
        return f"CCS_RETURN({value});"

    def math_header(self):
        return MATH_HEADER

    # -- pragmas -----------------------------------------------------------

    def open_loop(self, header, factor):
        factor = int(factor)
        # Catapult places the unroll pragma BEFORE the loop. A factor of 1 means
        # "do not unroll", which is the default, so emit nothing.
        if factor <= 1:
            return f"{header} {{\n"
        return f"#pragma hls_unroll {factor}\n{header} {{\n"

    def array_partition(self, var, factor, dim):
        """Record an interleave request; emits nothing at the call site.

        `hls_interleave` must attach to the array declaration, so this returns ""
        and `declaration_pragmas()` supplies the directive later. Requests against
        function *parameters* (the non-inlined op path) cannot be expressed in
        Catapult source at all and are dropped — see `dropped_partitions`.
        """
        factor = int(factor)
        if factor <= 1:
            return ""
        self._partitions[var] = max(self._partitions.get(var, 1), factor)
        return ""

    def declaration_pragmas(self, var, dims):
        """Interleave directive for `var`'s declaration, or "" if none pending."""
        factor = self._partitions.pop(var, 1)
        if factor <= 1:
            return ""
        factor = effective_pragma_factor(factor, dims[-1] if dims else 1)
        if factor <= 1:
            return ""
        return f"#pragma hls_interleave {factor}\n"

    @property
    def dropped_partitions(self):
        """Partition requests that had no declaration to attach to."""
        return list(self._partitions) + self._dropped_partitions

    def interface(self, drams):
        return []

    # -- build script ------------------------------------------------------

    def emit_script(self, drams, target, clock_period, tasks, output_filename):
        """Catapult script. Tasks: "csim" = SCVerify original C++ + testbench (Catapult's C simulation), "csynth" = synthesis to
        RTL (`go extract`), "cosim" = synthesis + SCVerify RTL (Verilog, Questa) vs C. Synthesis runs unless the task list is csim only."""
        tasks = list(tasks)
        verify = "csim" in tasks or "cosim" in tasks
        synth = bool(set(tasks) - {"csim"})
        lines = []
        lines.append("# Auto-generated TCL file for Catapult HLS")
        lines.append("options defaults")
        lines.append("options set Input/TargetPlatform x86_64")
        if "cosim" in tasks:
            lines.append(f"options set Flows/QuestaSIM/Path {QUESTA_BIN}")
        lines.append("")
        lines.append("project new -name catapult_top")
        if verify:
            lines.append("flow package require /SCVerify")
        lines.append("")
        lines.append("solution file add top.cpp")
        lines.append("solution file add top.h")
        if verify:
            lines.append("solution file add tb_top.cpp -exclude true")
            for dram in drams:
                lines.append(f"solution file add {dram['name']}.txt -exclude true")
        lines.append("")
        lines.append("go analyze")
        lines.append("")
        lines.append("directive set -OPT_CONST_MULTS simple_one_adder")
        for lib in (target or DEFAULT_LIBS):
            lines.append(f"solution library add {lib}")
        lines.append("directive set -PROTOTYPE_ROM false")
        lines.append("")
        lines.append("solution design set top -top")
        lines.append("go compile")
        if "csim" in tasks:
            lines.append("flow run /SCVerify/launch_make ./scverify/Verify_orig_cxx_osci.mk {} SIMTOOL=osci sim")
        if synth:
            lines.append("go libraries")
            lines.append("")
            lines.append(
                "directive set -CLOCKS {clk {"
                f"-CLOCK_PERIOD {clock_period} "
                "-CLOCK_EDGE rising -CLOCK_UNCERTAINTY 0.0 "
                f"-CLOCK_HIGH_TIME {float(clock_period) / 2} "
                "-RESET_SYNC_NAME rst -RESET_ASYNC_NAME arst_n -RESET_KIND sync "
                "-RESET_SYNC_ACTIVE high -RESET_ASYNC_ACTIVE low -ENABLE_ACTIVE high}}"
            )
            lines.append("")
            lines.append("go assembly")
            lines.append("go extract")
        if "cosim" in tasks:
            lines.append("flow run /SCVerify/launch_make ./scverify/Verify_rtl_v_msim.mk {} SIMTOOL=msim sim")
        lines.append("")
        lines.append("project save")
        lines.append("exit")

        with open(output_filename, "w") as f:
            f.write("\n".join(lines))

    def run_cmd(self):
        return ["catapult", "-shell", "-f", "run_hls.tcl"]
